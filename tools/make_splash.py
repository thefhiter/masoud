"""Render the wordmark into firmware/masoud_uno/brand_splash.h (1 bit per pixel).

usage: python make_splash.py path/to/Rubik.ttf [--text masoud] [--weight 800] [--max-w 112]
Font: Rubik (Google Fonts, OFL), a variable font with a weight axis.
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ap = argparse.ArgumentParser()
ap.add_argument("font")
ap.add_argument("--text", default="masoud")
ap.add_argument("--weight", type=int, default=800)
ap.add_argument("--max-w", type=int, default=112)
ap.add_argument("--size", type=int, default=40)
ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "firmware" / "masoud_uno" / "brand_splash.h"))
args = ap.parse_args()

font = ImageFont.truetype(args.font, args.size)
font.set_variation_by_axes([args.weight])
x0, y0, x1, y1 = font.getbbox(args.text)
img = Image.new("L", (x1 - x0 + 4, y1 - y0 + 4), 0)
ImageDraw.Draw(img).text((2 - x0, 2 - y0), args.text, font=font, fill=255)
if img.width > args.max_w:
    img = img.resize((args.max_w, round(img.height * args.max_w / img.width)), Image.LANCZOS)
bits = img.point(lambda v: 255 if v > 110 else 0).convert("1")
bits = bits.crop(bits.getbbox())
w, h = bits.size
stride = (w + 7) // 8
data = []
for y in range(h):
    for bx in range(stride):
        byte = 0
        for i in range(8):
            x = bx * 8 + i
            if x < w and bits.getpixel((x, y)):
                byte |= 0x80 >> i
        data.append(byte)

rows = [", ".join(f"0x{b:02X}" for b in data[i:i + stride]) for i in range(0, len(data), stride)]
Path(args.out).write_text(
    f"// Generated by tools/make_splash.py: the \"{args.text}\" wordmark,\n"
    f"// {Path(args.font).stem} weight {args.weight}, 1 bit per pixel, MSB first.\n"
    "#pragma once\n#include <avr/pgmspace.h>\n\n"
    f"const uint8_t WORDMARK_W = {w}, WORDMARK_H = {h}, WORDMARK_STRIDE = {stride};\n"
    f"const uint8_t WORDMARK[{len(data)}] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n",
    encoding="ascii")
print(f"wordmark {w}x{h}, {len(data)} bytes -> {args.out}")
